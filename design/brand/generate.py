#!/usr/bin/env python3
"""Generate every AirPlay TV brand asset from one geometry.

Outputs (run from the repo root: `python3 design/brand/generate.py`):
  app/src/main/res/drawable/logo_mark.xml, logo_mark_white.xml   in-app mark (vector)
  app/src/main/res/drawable/ic_launcher_{background,foreground,monochrome}.xml  adaptive layers
  app/src/main/res/mipmap-*/ic_launcher.png, ic_launcher_round.png  legacy icons (API < 26)
  app/src/main/res/drawable-xhdpi/banner.png                      Android TV banner (320x180 dp)
  design/brand/*.svg / *.png                                      editable sources and previews

Requires Pillow. The banner text uses Inter Bold from app/src/main/res/font.
"""
import math
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
BRAND = os.path.join(ROOT, "design", "brand")
FONT = os.path.join(RES, "font", "inter_bold.ttf")

NAME = "AirPlay TV"
SIGNAL = "#FC5858"   # brand red (Atv.Signal)
DEEP = "#8C2A2E"     # gradient end (Atv.Ambient2)
WHITE = "#FFFFFF"

# ---------- the mark, in a 96x96 viewport ----------
V = 96
STROKE = 5.0
WAVE_C = (48.0, 26.0)          # centre of the signal waves
WAVE_R = (9.0, 17.0)           # wave radii
DOT_R = 3.5                    # dot at the wave centre
TV = (12.0, 36.0, 84.0, 78.0)  # screen box (x0, y0, x1, y1), stroked
TV_R = 10.0
PLAY = [(43.0, 48.0), (58.0, 57.0), (43.0, 66.0)]
PLAY_ROUND = 3.0               # stroke used to round the triangle corners
STAND = (36.0, 84.0, 60.0, 89.0)
# visual bounds, used to centre the mark inside other canvases
BOUNDS = (TV[0] - STROKE / 2, WAVE_C[1] - WAVE_R[1] - STROKE / 2, TV[2] + STROKE / 2, STAND[3])


def wave_pts(r):
    a0, a1 = math.radians(225), math.radians(315)
    cx, cy = WAVE_C
    return (cx + r * math.cos(a0), cy + r * math.sin(a0)), (cx + r * math.cos(a1), cy + r * math.sin(a1))


def rrect_path(x0, y0, x1, y1, r):
    w, h = x1 - x0, y1 - y0
    return (f"M{x0 + r:g},{y0:g}h{w - 2 * r:g}a{r:g},{r:g} 0 0 1 {r:g},{r:g}v{h - 2 * r:g}"
            f"a{r:g},{r:g} 0 0 1 -{r:g},{r:g}h-{w - 2 * r:g}a{r:g},{r:g} 0 0 1 -{r:g},-{r:g}"
            f"v-{h - 2 * r:g}a{r:g},{r:g} 0 0 1 {r:g},-{r:g}z")


def circle_path(cx, cy, r):
    return f"M{cx - r:g},{cy:g}a{r:g},{r:g} 0 1 0 {2 * r:g},0a{r:g},{r:g} 0 1 0 -{2 * r:g},0z"


def wave_path(r):
    (x0, y0), (x1, y1) = wave_pts(r)
    return f"M{x0:.3f},{y0:.3f}A{r:g},{r:g} 0 0 1 {x1:.3f},{y1:.3f}"


PLAY_PATH = "M" + "L".join(f"{x:g},{y:g}" for x, y in PLAY) + "z"
STAND_R = (STAND[3] - STAND[1]) / 2


def mark_shapes(color, screen_alpha):
    """Shape list shared by the vector and SVG writers."""
    shapes = [
        ("stroke", rrect_path(*TV, TV_R), color, STROKE, screen_alpha),
        ("fill", PLAY_PATH, color, PLAY_ROUND, None),
        ("fill", rrect_path(*STAND, STAND_R), color, 0, None),
        ("fill", circle_path(*WAVE_C, DOT_R), color, 0, None),
    ]
    shapes += [("wave", wave_path(r), color, STROKE, None) for r in WAVE_R]
    return shapes


def argb(hex_color, alpha=1.0):
    return f"#{round(alpha * 255):02X}{hex_color.lstrip('#').upper()}"


# ---------- Android vector drawables ----------
def vector_paths(shapes, indent="    "):
    out = []
    for kind, d, color, width, screen_alpha in shapes:
        attrs = [f'android:pathData="{d}"']
        if kind == "stroke":
            attrs += [f'android:fillColor="{argb(color, screen_alpha)}"', f'android:strokeColor="{argb(color)}"',
                      f'android:strokeWidth="{width:g}"']
        elif kind == "wave":
            attrs += [f'android:strokeColor="{argb(color)}"', f'android:strokeWidth="{width:g}"',
                      'android:strokeLineCap="round"']
        else:
            attrs += [f'android:fillColor="{argb(color)}"']
            if width:
                attrs += [f'android:strokeColor="{argb(color)}"', f'android:strokeWidth="{width:g}"',
                          'android:strokeLineJoin="round"']
        out.append(f"{indent}<path\n{indent}    " + f"\n{indent}    ".join(attrs) + " />")
    return "\n".join(out)


def vector_doc(body, size, viewport):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by design/brand/generate.py; edit that script instead. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            f'    android:width="{size}dp"\n    android:height="{size}dp"\n'
            f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
            f"{body}\n</vector>\n")


def fg_transform(canvas=108.0, radius=31.0):
    """Scale/translate that centres the mark inside the adaptive-icon safe zone."""
    cx, cy = (BOUNDS[0] + BOUNDS[2]) / 2, (BOUNDS[1] + BOUNDS[3]) / 2
    pts = [(BOUNDS[0], TV[1] + TV_R), (BOUNDS[2], TV[1] + TV_R), (BOUNDS[0], TV[3]),
           (STAND[0], STAND[3]), (STAND[2], STAND[3]), (cx, BOUNDS[1])]
    pts += [p for r in WAVE_R for p in wave_pts(r + STROKE / 2)]
    far = max(math.hypot(x - cx, y - cy) for x, y in pts)
    s = radius / far
    return s, canvas / 2 - cx * s, canvas / 2 - cy * s


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def write_vectors():
    d = os.path.join(RES, "drawable")
    write(os.path.join(d, "logo_mark.xml"), vector_doc(vector_paths(mark_shapes(SIGNAL, 0.14)), 96, 96))
    write(os.path.join(d, "logo_mark_white.xml"), vector_doc(vector_paths(mark_shapes(WHITE, 0.14)), 96, 96))
    s, tx, ty = fg_transform()
    group = (f'    <group\n        android:scaleX="{s:.4f}"\n        android:scaleY="{s:.4f}"\n'
             f'        android:translateX="{tx:.4f}"\n        android:translateY="{ty:.4f}">\n'
             f"{{body}}\n    </group>")
    write(os.path.join(d, "ic_launcher_foreground.xml"),
          vector_doc(group.format(body=vector_paths(mark_shapes(WHITE, 0.16), "        ")), 108, 108))
    write(os.path.join(d, "ic_launcher_monochrome.xml"),
          vector_doc(group.format(body=vector_paths(mark_shapes(WHITE, 0.0), "        ")), 108, 108))
    bg = ('    <path android:pathData="M0,0h108v108h-108z">\n'
          '        <aapt:attr name="android:fillColor">\n'
          '            <gradient android:type="linear" android:startX="0" android:startY="0"\n'
          '                android:endX="108" android:endY="108">\n'
          f'                <item android:offset="0" android:color="{argb(SIGNAL)}" />\n'
          f'                <item android:offset="1" android:color="{argb(DEEP)}" />\n'
          '            </gradient>\n        </aapt:attr>\n    </path>')
    write(os.path.join(d, "ic_launcher_background.xml"), vector_doc(bg, 108, 108))


# ---------- SVG sources ----------
def svg_paths(shapes):
    out = []
    for kind, d, color, width, screen_alpha in shapes:
        if kind == "stroke":
            out.append(f'<path d="{d}" fill="{color}" fill-opacity="{screen_alpha:g}" stroke="{color}" stroke-width="{width:g}"/>')
        elif kind == "wave":
            out.append(f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{width:g}" stroke-linecap="round"/>')
        elif width:
            out.append(f'<path d="{d}" fill="{color}" stroke="{color}" stroke-width="{width:g}" stroke-linejoin="round"/>')
        else:
            out.append(f'<path d="{d}" fill="{color}"/>')
    return "\n  ".join(out)


GRAD = (f'<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">'
        f'<stop offset="0" stop-color="{SIGNAL}"/><stop offset="1" stop-color="{DEEP}"/></linearGradient></defs>')


def write_svgs():
    def svg(w, h, body, vb=None):
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="{vb or f"0 0 {w} {h}"}">\n'
                f"  {body}\n</svg>\n")
    write(os.path.join(BRAND, "Logos", "airplaytv-mark.svg"), svg(96, 96, svg_paths(mark_shapes(SIGNAL, 0.14))))
    write(os.path.join(BRAND, "Logos", "airplaytv-mark-white.svg"), svg(96, 96, svg_paths(mark_shapes(WHITE, 0.14))))
    s, tx, ty = fg_transform()
    fg = f'<g transform="translate({tx:.4f} {ty:.4f}) scale({s:.4f})">\n  {svg_paths(mark_shapes(WHITE, 0.16))}\n  </g>'
    write(os.path.join(BRAND, "AppIcon", "adaptive-background.svg"), svg(108, 108, f'{GRAD}<rect width="108" height="108" fill="url(#g)"/>'))
    write(os.path.join(BRAND, "AppIcon", "adaptive-foreground.svg"), svg(108, 108, fg))
    write(os.path.join(BRAND, "AppIcon", "app-icon.svg"),
          svg(108, 108, f'{GRAD}<rect width="108" height="108" rx="24" fill="url(#g)"/>\n  {fg}'))
    wm = (f'<g transform="translate(0 2) scale(0.5)">{svg_paths(mark_shapes(SIGNAL, 0.14))}</g>'
          f'<text x="58" y="34" font-family="Inter, sans-serif" font-weight="700" font-size="26" fill="#F5F5F7">{NAME}</text>')
    write(os.path.join(BRAND, "Logos", "airplaytv-wordmark.svg"), svg(206, 52, wm))


# ---------- raster (Pillow, 8x supersampled) ----------
SS = 8


def draw_mark(img, ox, oy, scale, color, screen_alpha):
    """Draw the mark onto an RGBA image at offset (ox, oy) with px-per-unit `scale`."""
    layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    rgb = Image.new("RGB", (1, 1), color).getpixel((0, 0))
    P = lambda x, y: (ox + x * scale, oy + y * scale)
    w = STROKE * scale
    x0, y0, x1, y1 = TV
    box = [*P(x0, y0), *P(x1, y1)]
    if screen_alpha:
        d.rounded_rectangle(box, radius=TV_R * scale, fill=rgb + (round(screen_alpha * 255),))
    # stroke centred on the path, like SVG/vector strokes
    d.rounded_rectangle([box[0] - w / 2, box[1] - w / 2, box[2] + w / 2, box[3] + w / 2],
                        radius=TV_R * scale + w / 2, outline=rgb + (255,), width=round(w))
    pts = [P(*p) for p in PLAY]
    d.polygon(pts, fill=rgb + (255,))
    rw = PLAY_ROUND * scale
    d.line(pts + [pts[0]], fill=rgb + (255,), width=round(rw), joint="curve")
    for p in pts:
        d.ellipse([p[0] - rw / 2, p[1] - rw / 2, p[0] + rw / 2, p[1] + rw / 2], fill=rgb + (255,))
    sx0, sy0, sx1, sy1 = STAND
    d.rounded_rectangle([*P(sx0, sy0), *P(sx1, sy1)], radius=STAND_R * scale, fill=rgb + (255,))
    cx, cy = P(*WAVE_C)
    d.ellipse([cx - DOT_R * scale, cy - DOT_R * scale, cx + DOT_R * scale, cy + DOT_R * scale], fill=rgb + (255,))
    for r in WAVE_R:
        R = r * scale
        d.arc([cx - R - w / 2, cy - R - w / 2, cx + R + w / 2, cy + R + w / 2], 225, 315, fill=rgb + (255,), width=round(w))
        for px, py in wave_pts(r):
            qx, qy = P(px, py)
            d.ellipse([qx - w / 2, qy - w / 2, qx + w / 2, qy + w / 2], fill=rgb + (255,))
    img.alpha_composite(layer)


def gradient(w, h):
    a = Image.new("RGB", (1, 1), SIGNAL).getpixel((0, 0))
    b = Image.new("RGB", (1, 1), DEEP).getpixel((0, 0))
    small = Image.new("RGBA", (64, 64))
    for y in range(64):
        for x in range(64):
            t = (x + y) / 126
            small.putpixel((x, y), tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3)) + (255,))
    return small.resize((w, h), Image.BILINEAR)


def icon_canvas(px):
    """Full 108-unit adaptive icon (background + foreground) rendered at px*SS."""
    big = px * SS
    img = gradient(big, big)
    s, tx, ty = fg_transform()
    k = big / 108
    draw_mark(img, tx * k, ty * k, s * k, WHITE, 0.16)
    return img


def legacy_icons():
    densities = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
    for name, size in densities.items():
        full = icon_canvas(round(size * 108 / 72))  # legacy icons show the central 72 of 108 units
        big = full.size[0]
        inset = round(big * 18 / 108)
        crop = full.crop((inset, inset, big - inset, big - inset)).resize((size * SS, size * SS), Image.LANCZOS)
        for fname, mask_kind in (("ic_launcher.png", "square"), ("ic_launcher_round.png", "round")):
            mask = Image.new("L", crop.size, 0)
            md = ImageDraw.Draw(mask)
            if mask_kind == "round":
                md.ellipse([0, 0, crop.size[0] - 1, crop.size[1] - 1], fill=255)
            else:
                md.rounded_rectangle([0, 0, crop.size[0] - 1, crop.size[1] - 1], radius=crop.size[0] * 0.2, fill=255)
            out = Image.new("RGBA", crop.size, (0, 0, 0, 0))
            out.paste(crop, (0, 0), mask)
            out = out.resize((size, size), Image.LANCZOS)
            path = os.path.join(RES, f"mipmap-{name}", fname)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            out.save(path, optimize=True)


def banner(w, h, path):
    big_w, big_h = w * SS, h * SS
    img = gradient(big_w, big_h)
    mark_h = 0.56 * big_h
    bw, bh = BOUNDS[2] - BOUNDS[0], BOUNDS[3] - BOUNDS[1]
    scale = mark_h / bh
    font_px = round(0.22 * big_h)
    font = ImageFont.truetype(FONT, font_px)
    gap = 0.07 * big_w
    text_w = ImageDraw.Draw(img).textlength(NAME, font=font)
    max_text = big_w * 0.92 - bw * scale - gap
    if text_w > max_text:
        font = ImageFont.truetype(FONT, round(font_px * max_text / text_w))
        text_w = ImageDraw.Draw(img).textlength(NAME, font=font)
    total = bw * scale + gap + text_w
    left = (big_w - total) / 2
    draw_mark(img, left - BOUNDS[0] * scale, (big_h - mark_h) / 2 - BOUNDS[1] * scale, scale, WHITE, 0.16)
    d = ImageDraw.Draw(img)
    d.text((left + bw * scale + gap, big_h / 2), NAME, font=font, fill=WHITE, anchor="lm")
    img = img.convert("RGB").resize((w, h), Image.LANCZOS)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path, optimize=True)


def previews():
    icon = icon_canvas(512 * 108 // 108).resize((512, 512), Image.LANCZOS)
    mask = Image.new("L", (512, 512), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, 511, 511], radius=112, fill=255)
    out = Image.new("RGBA", (512, 512), (0, 0, 0, 0))
    out.paste(icon, (0, 0), mask)
    out.save(os.path.join(BRAND, "AppIcon", "app-icon-512.png"), optimize=True)
    banner(1280, 720, os.path.join(BRAND, "AppIcon", "tv-banner-1280x720.png"))


if __name__ == "__main__":
    write_vectors()
    write_svgs()
    legacy_icons()
    banner(640, 360, os.path.join(RES, "drawable-xhdpi", "banner.png"))
    previews()
    print("brand assets generated")
